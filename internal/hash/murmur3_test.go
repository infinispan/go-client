func TestHash(t *testing.T) {
	for _, tc := range testVectors {
		t.Run(tc.name, func(t *testing.T) {
			got := Hash(tc.input)
			if got != tc.hash {
				t.Errorf("Hash(%v) = %d, want %d", tc.input, got, tc.hash)
			}
		})
	}
}

func TestHashDeterministic(t *testing.T) {
	key := []byte("deterministic-test")
	h1 := Hash(key)
	for i := 0; i < 1000; i++ {
		if h := Hash(key); h != h1 {
			t.Fatalf("iteration %d: Hash changed from %d to %d", i, h1, h)
		}
	}
}

